-- BTC Swing V5 F2 initial PostgreSQL schema. New database only; no historical ETL.
-- Legacy-compatible timestamps kept as ISO8601 TEXT in V4 domain tables.
-- This preserves exact V4 API serialization; a future typed timestamp migration requires contract tests.
-- All operations in tests occur exclusively in Neon preview.
CREATE TABLE IF NOT EXISTS trade_opportunities (
    setup_id TEXT PRIMARY KEY,
    coin TEXT NOT NULL,
    side TEXT NOT NULL CHECK(side IN ('LONG', 'SHORT')),
    support DOUBLE PRECISION NOT NULL,
    resistance DOUBLE PRECISION NOT NULL,
    origin_price DOUBLE PRECISION NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('ACTIVE_UNTRADED', 'ACTIVE_TRADED', 'INVALIDATED')),
    created_at TEXT NOT NULL,
    executed_at TEXT,
    invalidated_at TEXT,
    invalidation_reason TEXT
);

CREATE INDEX IF NOT EXISTS idx_trade_opportunities_status
ON trade_opportunities (status);

CREATE UNIQUE INDEX IF NOT EXISTS idx_trade_opportunities_single_active
ON trade_opportunities (coin)
WHERE status IN ('ACTIVE_UNTRADED', 'ACTIVE_TRADED');

CREATE TABLE IF NOT EXISTS trade_signals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setup_id TEXT REFERENCES trade_opportunities(setup_id),
    created_at TEXT NOT NULL,
    origin TEXT NOT NULL CHECK(origin IN ('BACKTEST','PAPER','LIVE')),
    side TEXT NOT NULL CHECK(side IN ('LONG','SHORT')),
    state_at_entry TEXT NOT NULL CHECK(state_at_entry IN ('NO_TRADE','WATCH','CONFIRMED','HIGH','VERY_HIGH')),
    daily_swing_candles_at_signal INTEGER,
    entry_reference DOUBLE PRECISION NOT NULL,
    stop_loss DOUBLE PRECISION NOT NULL,
    tp1 DOUBLE PRECISION NOT NULL,
    tp2 DOUBLE PRECISION NOT NULL,
    tp3 DOUBLE PRECISION NOT NULL,
    rr1 DOUBLE PRECISION NOT NULL,
    rr2 DOUBLE PRECISION NOT NULL,
    rr3 DOUBLE PRECISION NOT NULL,
    weighted_rr DOUBLE PRECISION NOT NULL,
    expectancy_r DOUBLE PRECISION,
    historical_win_rate DOUBLE PRECISION,
    statistical_samples INTEGER NOT NULL DEFAULT 0,
    margin_usd DOUBLE PRECISION NOT NULL,
    leverage INTEGER NOT NULL,
    notional_usd DOUBLE PRECISION NOT NULL,
    status TEXT NOT NULL DEFAULT 'OPEN',
    fingerprint TEXT UNIQUE,
    tp1_hit_at TEXT,
    tp2_hit_at TEXT,
    tp3_hit_at TEXT,
    sl_hit_at TEXT,
    remaining_fraction DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    realized_pnl_usd DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    realized_r DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    closed_at TEXT,
    last_processed_candle_close_ms INTEGER
);

CREATE TABLE IF NOT EXISTS trade_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_id INTEGER NOT NULL REFERENCES trade_signals(id) ON DELETE CASCADE,
    event_at TEXT NOT NULL,
    event_type TEXT NOT NULL,
    price DOUBLE PRECISION,
    fraction_closed DOUBLE PRECISION,
    pnl_usd DOUBLE PRECISION,
    pnl_r DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS trade_results (
    signal_id INTEGER PRIMARY KEY REFERENCES trade_signals(id) ON DELETE CASCADE,
    closed_at TEXT,
    realized_pnl_usd DOUBLE PRECISION,
    realized_r DOUBLE PRECISION,
    max_favorable_excursion DOUBLE PRECISION,
    max_adverse_excursion DOUBLE PRECISION,
    holding_hours DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS telegram_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL,
    event_key TEXT NOT NULL UNIQUE,
    sent_at TEXT NOT NULL,
    success INTEGER NOT NULL DEFAULT 1 CHECK(success IN (0,1)),
    telegram_message_id TEXT,
    error_message TEXT,
    signal_id INTEGER REFERENCES trade_signals(id)
);

CREATE TABLE IF NOT EXISTS app_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS engine_runtime_state (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS engine_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TEXT NOT NULL,
    algorithm_version TEXT NOT NULL,
    price DOUBLE PRECISION,
    signal_state TEXT NOT NULL,
    signal_side TEXT,
    trade_window_open INTEGER NOT NULL CHECK(trade_window_open IN (0,1)),
    block_reason TEXT,
    setup_id TEXT,
    setup_active INTEGER NOT NULL DEFAULT 0 CHECK(setup_active IN (0,1)),
    snapshot_json TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_engine_snapshots_created_at
ON engine_snapshots (created_at);

CREATE INDEX IF NOT EXISTS idx_engine_snapshots_setup_id
ON engine_snapshots (setup_id);

CREATE UNIQUE INDEX IF NOT EXISTS idx_trade_event_once_per_type
ON trade_events (signal_id, event_type);

CREATE INDEX IF NOT EXISTS idx_trade_signals_status
ON trade_signals (status);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('ADMIN', 'VIEWER')),
    enabled INTEGER NOT NULL DEFAULT 1 CHECK(enabled IN (0, 1)),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    last_login_at TEXT
);

CREATE TABLE IF NOT EXISTS auth_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_token_hash TEXT NOT NULL UNIQUE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    last_seen_at TEXT NOT NULL,
    revoked_at TEXT
);

CREATE INDEX IF NOT EXISTS idx_auth_sessions_token_hash
ON auth_sessions (session_token_hash);

CREATE INDEX IF NOT EXISTS idx_auth_sessions_user_id
ON auth_sessions (user_id);

CREATE TABLE IF NOT EXISTS auth_login_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_key TEXT NOT NULL UNIQUE,
    failed_count INTEGER NOT NULL DEFAULT 0,
    first_failed_at TEXT NOT NULL,
    last_failed_at TEXT NOT NULL,
    locked_until TEXT
);

CREATE INDEX IF NOT EXISTS idx_auth_login_attempts_locked
ON auth_login_attempts (locked_until);

CREATE UNIQUE INDEX IF NOT EXISTS idx_trade_signals_setup_id_unique ON trade_signals (setup_id) WHERE setup_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username_ci ON users (lower(username));

CREATE INDEX IF NOT EXISTS idx_telegram_events_type_success ON telegram_events (event_type, success, sent_at);

CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT PRIMARY KEY, checksum TEXT, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());

CREATE TABLE IF NOT EXISTS operational_logs (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), service TEXT NOT NULL, severity TEXT NOT NULL CHECK (severity IN ('INFO','WARN','ERROR')), cycle_key TEXT, code TEXT NOT NULL, message TEXT NOT NULL CHECK (length(message) <= 2000));

CREATE INDEX IF NOT EXISTS idx_operational_logs_created ON operational_logs (created_at DESC);

CREATE TABLE IF NOT EXISTS worker_heartbeat (worker_key TEXT PRIMARY KEY, last_seen_at TIMESTAMPTZ NOT NULL, last_success_at TIMESTAMPTZ, status TEXT NOT NULL CHECK(status IN ('OK','ERROR','RETRASADO','SIN DATOS')), cycle_key TEXT, details TEXT);

CREATE TABLE IF NOT EXISTS notification_outbox (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_key TEXT NOT NULL UNIQUE, event_type TEXT NOT NULL, signal_id BIGINT REFERENCES trade_signals(id), payload TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','SENT','FAILED')), attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts>=0), next_attempt_at TIMESTAMPTZ, last_error TEXT);

CREATE TABLE IF NOT EXISTS push_subscriptions (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, endpoint_hash TEXT NOT NULL UNIQUE, endpoint TEXT NOT NULL, p256dh TEXT NOT NULL, auth_secret TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), revoked_at TIMESTAMPTZ);